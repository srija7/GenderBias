def plot_pupil_diameter(trial_data, trial_number):
    plt.figure(figsize=(8, 4))  # Adjust the figsize here

    # Filter data where there are no messages
    filtered_data = trial_data[trial_data['message'] == '0']

    # Calculate mean values for both left and right pupil diameters
    mean_pupil_diameter = (filtered_data['leftPupilDiameter'] + filtered_data['rightPupilDiameter']) / 2

    # Plot mean values
    plt.plot(filtered_data['system time'], mean_pupil_diameter, label='Average Pupil Diameter', color='blue')

    # Draw vertical red dotted lines for specific messages
    trial_messages = trial_data[trial_data['message'] != '0']
    for idx, row in trial_messages.iterrows():
        if 'Start of Trail' in row['message'] or 'End of Trail' in row['message'] or 'Intial selected images' in row['message'] or 'blank screen ends' in row['message'] or 'image_to_replace' in row['message'] or 'Time Taken' in row['message']:
            plt.axvline(x=row['system time'], color='red', linestyle='--', alpha=0.5)
            if 'Start of Trail' in row['message']:
                plt.text(row['system time'], 1, 'Initial images', color='black', rotation=90)
            elif 'Intial selected images' in row['message']:
                plt.text(row['system time'], 1, '+ sign', color='black', rotation=90)
            elif 'blank screen ends' in row['message']:
                plt.text(row['system time'], 1, 'Modified images', color='black', rotation=90)
            elif 'image_to_replace' in row['message']:
                plt.text(row['system time'], 1, 'Question', color='black', rotation=90)
            elif 'Time Taken' in row['message']:
                plt.text(row['system time'], 1, '+ sign', color='black', rotation=90)
            elif 'End of Trail' in row['message']:
                plt.text(row['system time'], 1, 'End', color='black', rotation=90)

    # Extract replacement condition from the message column
    replacement_condition = None
    for msg in trial_data['message']:
        if 'replacement_condition' in msg:
            replacement_condition = msg.split('replacement_condition: ')[1]
            break

    # Set the plot title including the trail condition
    if replacement_condition:
        plt.title(f'Average Pupil Diameter: Trial {trial_number}: {replacement_condition}')
    else:
        plt.title(f'Average Pupil Diameter: Trial {trial_number}')

    plt.xlabel('System Time')
    plt.ylabel('Pupil Diameter')
    plt.ylim(0, 6)  # Set the y-axis range
    plt.legend()
    plt.show()

